def inject():
    with open('data/mid_maintenance_electrician.json', 'r', encoding='utf-8') as f:
        data = json.load(f)

    injected_count = 0
    for q in data['questions']:
        qid = q['id']
        if qid in EXPLANATIONS:
            q['explanation'] = EXPLANATIONS[qid]
            injected_count += 1
        elif 'explanation' not in q:
            q['explanation'] = ""

    # 寫回 JSON
    with open('data/mid_maintenance_electrician.json', 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    # 寫回 JS
    with open('data/mid_maintenance_electrician.js', 'w', encoding='utf-8') as f:
        f.write('window.RAW_QUESTION_DATA = ' + json.dumps(data, ensure_ascii=False) + ';')

    print(f"Successfully injected explanations into {injected_count} questions!")

if __name__ == '__main__':
    inject()
